"""Generate original SYNTHETIC pages, labels and landmarks (no real accuracy).

Run: python3 -m tools.bubble_eval.generate_fixtures --output /tmp/bubble-fixtures
Output must be an empty/nonexistent directory, avoiding user asset overwrites.
Labels are rectangles authored in the specification, not detector outputs.
Transition strips test original coordinate extents, not Android decoder parity.
"""

import argparse
import hashlib
import json
from pathlib import Path

from .png import write_gray


def _json(path, value):
    path.write_text(json.dumps(value, sort_keys=True, indent=2)+'\n', encoding='utf-8')


def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(output):
    output = Path(output)
    if output.exists() and any(output.iterdir()):
        raise ValueError("fixture output must be empty; refusing to overwrite")
    output.mkdir(parents=True, exist_ok=True)
    spec_path = Path(__file__).resolve().parents[2]/'qa/bubble/fixtures/specification.json'
    specification = json.loads(spec_path.read_text(encoding='utf-8'))
    samples, landmarks = [], []
    for case in specification['pages']:
        identity = case['sample_id']
        width, height = case['width'], case['height']
        page = bytearray([192])*(width*height)
        for row_index in range(height):
            for column_index in range(width):
                if column_index in (0, width-1) or row_index in (0, height-1):
                    page[row_index*width+column_index] = 0
        instances = []
        for label in case['instances']:
            left, top, right, bottom = label['box']
            coverage = bytearray(width*height)
            for row_index in range(top, bottom):
                for column_index in range(left, right):
                    coverage[row_index*width+column_index] = 255
                    page[row_index*width+column_index] = 255
            mask_path = output/(identity+'-'+label['id']+'.png')
            write_gray(mask_path, width, height, bytes(coverage))
            instances.append({'id': label['id'], 'box': label['box'],
                              'mask_path': mask_path.name, 'mask_sha256': _sha(mask_path)})
        page[(height//2)*width] = 0
        asset_path = output/(identity+'.png')
        write_gray(asset_path, width, height, bytes(page))
        annotation_path = output/(identity+'.annotation.json')
        _json(annotation_path, {'schema_version': '1.0', 'sample_id': identity,
                               'width': width, 'height': height, 'completeness': 'mask',
                               'instances': instances, 'groups': case.get('groups', [
                                   {'id': 'singleton-'+label['id'], 'members': [label['id']]}
                                   for label in case['instances']]),
                               'ignore_regions': []})
        samples.append({'sample_id': identity, 'source_group': 'original-synthetic-v1',
                        'split': 'regression', 'tags': case['tags'], 'rights_id': 'synthetic-original',
                        'asset': {'path': asset_path.name, 'sha256': _sha(asset_path),
                                  'width': width, 'height': height},
                        'annotation': {'path': annotation_path.name,
                                       'sha256': _sha(annotation_path), 'completeness': 'mask'}})
        landmarks.append({'sample_id': identity, 'last_pixel_center': [width-.5, height-.5],
                          'foreground_pixels': sum((instance['box'][2]-instance['box'][0])*(instance['box'][3]-instance['box'][1])
                                                   for instance in case['instances'])})
    manifest = {'schema_version': '1.0', 'dataset_id': 'synthetic-foundation-v1',
                'revision': '1', 'kind': 'synthetic', 'samples': samples}
    _json(output/'manifest.json', manifest)
    evidence = output/'rights-evidence.txt'
    evidence.write_text('Original geometric synthetic test artwork generated by tools/bubble_eval/generate_fixtures.py.\nNo third-party source images or real comic pages are used.\nDedicated to the public domain under CC0-1.0 for evaluation and redistribution.\n', encoding='utf-8')
    _json(output/'rights.json', {'schema_version': '1.0', 'records': [{
        'rights_id': 'synthetic-original', 'status': 'approved', 'license': 'CC0-1.0',
        'holder': 'Anagno synthetic fixture contributors',
        'allowed_uses': ['evaluation', 'redistribution'],
        'evidence': {'path': evidence.name, 'sha256': _sha(evidence)}}]})
    _json(output/'landmarks.json', {'schema_version': '1.0', 'kind': 'synthetic', 'pages': landmarks})
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    generate(args.output)


if __name__ == '__main__':
    main()
